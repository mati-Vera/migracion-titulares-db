-- Validación de titulares activos PF con matrícula inexistente (25/09/2026).
-- Paso 1 del pedido: dataset de análisis, UNA FILA POR TITULAR ACTIVO HUÉRFANO.
--
-- Universo: filas vivas de DIG_DOC_R00_B2 (NVL(ELIMINADO,0)=0) de personas
-- físicas cuyo ID_MATRICULA no existe en DIG_DOC_R00. Mismo universo que
-- docs/Titulares_activos_con_matricula_inexistente.csv (477 filas al 24/09).
-- Clave física de la fila: (ID_MATRICULA, NU_SEQUENCE) — PK de B2.
--
-- Solo lectura. No crea tablas ni vistas: todo va en CTEs y se exporta con
--   RunQuery ../queries/validacion_huerfanos_01_dataset.sql --csv ../out/validacion_huerfanos_01_dataset_<fecha>
--
-- Notas de interpretación (no asumir):
--   * "Documento" = R62.NU_DOCUMENTO sin placeholders. Mismo documento NO
--     implica misma persona (CLAUDE.md §7, personas mezcladas): los contadores
--     por documento son indicios, no identidad.
--   * B2 no tiene NU_MATRICULA ni ID_FORMULARIO propios. ID_FORMULARIO acá es
--     el de la persona (R62.ID_FORMULARIO = B2.CD_PERSONA). NU_MATRICULA_POR_ID
--     es el NU_MATRICULA de la matrícula real cuyo NU_MATRICULA = este ID
--     (hipótesis "clave equivocada"); NU_MATRICULA_R20 el que registran las
--     minutas R20 para ese mismo ID (si existen).
--   * B4 no tiene ELIMINADO; B2/B5 se filtran con NVL(ELIMINADO,0)=0.

WITH O AS (
    SELECT b.ID_MATRICULA, b.NU_SEQUENCE, b.CD_PERSONA, b.CD_SITUACION,
           b.DT_DESDE, b.TM_DESDE, b.NU_NUMERADOR, b.NU_DENOMINADOR, b.DS_PORCENTAJE,
           b.CD_COLUM_2, b.NU_ASIEN_2, b.NU_CASO_ORIGEN, b.CD_ESTA_2,
           b.DT_ALTA, b.DT_MODIFICACION, b.CD_USER_STORE, b.CD_USER_UPDATE,
           NVL(b.ELIMINADO,0) AS ELIMINADO, b.RECIENTE, b.MIG_FHPI_ID, b.DS_OBSERVA,
           p.TP_PERSONA, p.NU_DOCUMENTO, p.TP_DOCUMENTO, p.CD_SEXO, p.NU_CUIL_CUIT,
           p.NM_APELLIDO, p.NM_NOMBRE, p.CD_USER_STORE AS CD_USER_STORE_PERS,
           p.DT_STORE AS DT_STORE_PERS, p.MIG_ID_PERSONA, p.ID_PERSONA_RGDB1,
           CASE WHEN p.NU_DOCUMENTO IS NULL OR REGEXP_LIKE(p.NU_DOCUMENTO,'^0+$')
                  OR p.NU_DOCUMENTO IN ('99907804','1') THEN NULL
                ELSE p.NU_DOCUMENTO END AS DOC_OK
    FROM SIRCLAN.DIG_DOC_R00_B2 b
    JOIN SIRCLAN.DIG_DOC_R62 p ON p.ID_FORMULARIO = b.CD_PERSONA AND p.TP_PERSONA = 'PF'
    WHERE NVL(b.ELIMINADO,0) = 0
      AND NOT EXISTS (SELECT 1 FROM SIRCLAN.DIG_DOC_R00 i WHERE i.ID_MATRICULA = b.ID_MATRICULA)
),
-- Titularidad viva de la misma persona en matrícula existente.
PER_OTRA AS (
    SELECT x.CD_PERSONA, COUNT(*) AS N, COUNT(DISTINCT x.ID_MATRICULA) AS NMAT
    FROM SIRCLAN.DIG_DOC_R00_B2 x JOIN SIRCLAN.DIG_DOC_R00 i ON i.ID_MATRICULA = x.ID_MATRICULA
    WHERE NVL(x.ELIMINADO,0) = 0 AND x.CD_PERSONA IN (SELECT CD_PERSONA FROM O)
    GROUP BY x.CD_PERSONA
),
-- Idem por documento (cualquier CD_PERSONA con ese documento).
DOC_OTRA AS (
    SELECT q.NU_DOCUMENTO, COUNT(*) AS N, COUNT(DISTINCT x.ID_MATRICULA) AS NMAT,
           COUNT(DISTINCT x.CD_PERSONA) AS NPERS
    FROM SIRCLAN.DIG_DOC_R62 q
    JOIN SIRCLAN.DIG_DOC_R00_B2 x ON x.CD_PERSONA = q.ID_FORMULARIO
    JOIN SIRCLAN.DIG_DOC_R00 i ON i.ID_MATRICULA = x.ID_MATRICULA
    WHERE NVL(x.ELIMINADO,0) = 0 AND q.TP_PERSONA = 'PF'
      AND q.NU_DOCUMENTO IN (SELECT DOC_OK FROM O WHERE DOC_OK IS NOT NULL)
    GROUP BY q.NU_DOCUMENTO
),
-- Histórico (B4) y no vigentes (B5) de la persona / del documento, en cualquier matrícula.
PER_B4 AS (
    SELECT h.CD_PERSONA_H AS CD_PERSONA, COUNT(*) AS N,
           SUM(CASE WHEN EXISTS (SELECT 1 FROM SIRCLAN.DIG_DOC_R00 i WHERE i.ID_MATRICULA = h.ID_MATRICULA) THEN 1 ELSE 0 END) AS N_MAT_EXISTENTE
    FROM SIRCLAN.DIG_DOC_R00_B4 h WHERE h.CD_PERSONA_H IN (SELECT CD_PERSONA FROM O)
    GROUP BY h.CD_PERSONA_H
),
DOC_B4 AS (
    SELECT q.NU_DOCUMENTO, COUNT(*) AS N
    FROM SIRCLAN.DIG_DOC_R62 q JOIN SIRCLAN.DIG_DOC_R00_B4 h ON h.CD_PERSONA_H = q.ID_FORMULARIO
    WHERE q.TP_PERSONA = 'PF' AND q.NU_DOCUMENTO IN (SELECT DOC_OK FROM O WHERE DOC_OK IS NOT NULL)
    GROUP BY q.NU_DOCUMENTO
),
PER_B5 AS (
    SELECT v.CD_PERSONA_P AS CD_PERSONA, COUNT(*) AS N
    FROM SIRCLAN.DIG_DOC_R00_B5 v
    WHERE NVL(v.ELIMINADO,0) = 0 AND v.CD_PERSONA_P IN (SELECT CD_PERSONA FROM O)
    GROUP BY v.CD_PERSONA_P
),
-- Mismo caso de origen en una matrícula existente (B2 vivo) y, vía asientos
-- R14 del caso, matrículas existentes que el trámite tocó.
CASO_OTRA AS (
    SELECT x.NU_CASO_ORIGEN, COUNT(*) AS N, COUNT(DISTINCT x.ID_MATRICULA) AS NMAT,
           MIN(x.ID_MATRICULA) AS MIN_ID
    FROM SIRCLAN.DIG_DOC_R00_B2 x JOIN SIRCLAN.DIG_DOC_R00 i ON i.ID_MATRICULA = x.ID_MATRICULA
    WHERE NVL(x.ELIMINADO,0) = 0
      AND x.NU_CASO_ORIGEN IN (SELECT NU_CASO_ORIGEN FROM O WHERE NU_CASO_ORIGEN IS NOT NULL)
    GROUP BY x.NU_CASO_ORIGEN
),
CASO_R14 AS (
    SELECT r.NU_CASO, COUNT(*) AS N_ASIENTOS,
           COUNT(DISTINCT CASE WHEN i.ID_MATRICULA IS NOT NULL THEN r.ID_MATRICULA END) AS NMAT_EXISTENTE,
           COUNT(DISTINCT CASE WHEN i.ID_MATRICULA IS NULL THEN r.ID_MATRICULA END) AS NMAT_INEXISTENTE,
           MIN(i.ID_MATRICULA) AS MIN_ID_EXISTENTE
    FROM SIRCLAN.DIG_DOC_R14 r LEFT JOIN SIRCLAN.DIG_DOC_R00 i ON i.ID_MATRICULA = r.ID_MATRICULA
    WHERE r.NU_CASO IN (SELECT NU_CASO_ORIGEN FROM O WHERE NU_CASO_ORIGEN IS NOT NULL)
    GROUP BY r.NU_CASO
),
CASO_BPM AS (
    SELECT c.DOCUMENT_KEY_MAIN, c.CD_PROCESS, c.CD_STATE, c.DT_INITIATED, c.DT_TERMINATED, c.CD_USUARIO_STORE
    FROM SIRCLAN."CASE" c
    WHERE c.DOCUMENT_KEY_MAIN IN (SELECT NU_CASO_ORIGEN FROM O WHERE NU_CASO_ORIGEN IS NOT NULL)
),
-- Rastro del ID huérfano en el resto del formulario R00 y en tablas de migración.
IDS AS (SELECT DISTINCT ID_MATRICULA AS ID FROM O),
TRAZA AS (
    SELECT IDS.ID,
        (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00_B2 x WHERE x.ID_MATRICULA = IDS.ID) AS B2_FILAS_TOTAL_ID,
        (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00_B4 x WHERE x.ID_MATRICULA = IDS.ID) AS B4_FILAS_ID,
        (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00_B5 x WHERE x.ID_MATRICULA = IDS.ID) AS B5_FILAS_ID,
        (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00_A1 x WHERE x.ID_MATRICULA = IDS.ID)
      + (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00_A2 x WHERE x.ID_MATRICULA = IDS.ID)
      + (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00_B1 x WHERE x.ID_MATRICULA = IDS.ID)
      + (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00_B3 x WHERE x.ID_MATRICULA = IDS.ID)
      + (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00_B8 x WHERE x.ID_MATRICULA = IDS.ID) AS R00_HIJAS_FILAS,
        (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R14 x WHERE x.ID_MATRICULA = IDS.ID) AS R14_ASIENTOS_ID,
        (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00_B2_20170902 x WHERE x.ID_MATRICULA = IDS.ID) AS B2_SNAPSHOT_2017_ID,
        (SELECT COUNT(*) FROM SIRCLAN.V_PROCEDENCIA_DOMNIO_MIG x WHERE x.ID_MATRICULA = IDS.ID) AS EN_PROCEDENCIA_MIG,
        (SELECT COUNT(*) FROM SIRCLAN.TOMOS_MAL_CREADOS x WHERE x.ID_MATR_TOMO = IDS.ID OR x.ID_MATR_SIRC = IDS.ID) AS EN_TOMOS_MAL_CREADOS,
        (SELECT COUNT(*) FROM SIRCWEB.DIG_DOC_R00 x WHERE x.ID_MATRICULA = IDS.ID) AS EN_SIRCWEB_R00,
        (SELECT MIN(i.ID_MATRICULA) FROM SIRCLAN.DIG_DOC_R00 i WHERE i.NU_MATRICULA = IDS.ID) AS ID_REAL_SI_ES_NU_MATRICULA,
        (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00 i WHERE i.NU_MATRICULA = IDS.ID) AS EXISTE_MATRICULA_POR_NU,
        (SELECT MIN(r.NU_MATRICULA) FROM SIRCLAN.DIG_DOC_R20 r WHERE r.ID_MATRICULA = IDS.ID) AS NU_MATRICULA_R20,
        (SELECT MAX(i.ID_MATRICULA) FROM SIRCLAN.DIG_DOC_R00 i WHERE i.ID_MATRICULA < IDS.ID) AS R00_ID_ANTERIOR,
        (SELECT MIN(i.ID_MATRICULA) FROM SIRCLAN.DIG_DOC_R00 i WHERE i.ID_MATRICULA > IDS.ID) AS R00_ID_SIGUIENTE
    FROM IDS
),
BASE AS (
    SELECT O.*,
        COUNT(*) OVER (PARTITION BY O.ID_MATRICULA, O.CD_PERSONA) AS CANT_REG_MISMA_MAT_PERSONA,
        CASE WHEN O.DOC_OK IS NULL THEN NULL
             ELSE COUNT(*) OVER (PARTITION BY O.ID_MATRICULA, O.DOC_OK) END AS CANT_REG_MISMA_MAT_DOCUMENTO,
        CASE WHEN O.DOC_OK IS NULL THEN NULL
             ELSE COUNT(DISTINCT O.CD_PERSONA) OVER (PARTITION BY O.ID_MATRICULA, O.DOC_OK) END AS CANT_PERSONAS_MISMA_MAT_DOC,
        MIN(O.DT_ALTA) OVER (PARTITION BY O.ID_MATRICULA, O.CD_PERSONA) AS FECHA_PRIMER_REGISTRO,
        MAX(O.DT_ALTA) OVER (PARTITION BY O.ID_MATRICULA, O.CD_PERSONA) AS FECHA_ULTIMO_REGISTRO,
        ROW_NUMBER() OVER (PARTITION BY O.ID_MATRICULA, O.CD_PERSONA
                           ORDER BY O.DT_ALTA NULLS FIRST, O.NU_SEQUENCE) AS ORDEN_EN_GRUPO,
        COUNT(*) OVER (PARTITION BY O.ID_MATRICULA) AS FILAS_HUERFANAS_PF_EN_ID
    FROM O
)
SELECT
    B.ID_MATRICULA || '-' || B.NU_SEQUENCE                   AS ID_REGISTRO,
    B.ID_MATRICULA, B.NU_SEQUENCE, B.CD_PERSONA,
    B.CD_PERSONA                                             AS ID_FORMULARIO_PERSONA,
    B.NU_DOCUMENTO, B.TP_DOCUMENTO, B.CD_SEXO, B.NU_CUIL_CUIT,
    TRIM(B.NM_APELLIDO) || ', ' || TRIM(B.NM_NOMBRE)         AS NOMBRE_COMPLETO,
    B.TP_PERSONA, B.CD_SITUACION, B.ELIMINADO, B.RECIENTE,
    B.NU_CASO_ORIGEN, B.CD_USER_STORE, B.CD_USER_UPDATE,
    TO_CHAR(B.DT_ALTA, 'YYYY-MM-DD HH24:MI:SS')              AS DT_ALTA,
    TO_CHAR(B.DT_MODIFICACION, 'YYYY-MM-DD HH24:MI:SS')      AS DT_MODIFICACION,
    TO_CHAR(B.DT_DESDE, 'YYYY-MM-DD')                        AS DT_DESDE,
    TO_CHAR(B.TM_DESDE, 'YYYY-MM-DD HH24:MI:SS')             AS TM_DESDE,
    B.NU_NUMERADOR, B.NU_DENOMINADOR, B.DS_PORCENTAJE, B.CD_COLUM_2, B.NU_ASIEN_2,
    B.CD_ESTA_2, B.MIG_FHPI_ID, B.DS_OBSERVA,
    B.CD_USER_STORE_PERS, TO_CHAR(B.DT_STORE_PERS, 'YYYY-MM-DD') AS DT_STORE_PERS,
    B.MIG_ID_PERSONA, B.ID_PERSONA_RGDB1,
    -- Indicadores derivados pedidos
    0                                                        AS EXISTE_MATRICULA_POR_ID,
    T.EXISTE_MATRICULA_POR_NU,
    T.ID_REAL_SI_ES_NU_MATRICULA,
    T.NU_MATRICULA_R20,
    NVL(PO.N, 0)                                             AS PERSONA_OTRA_TIT_ACTIVA_FILAS,
    NVL(PO.NMAT, 0)                                          AS PERSONA_OTRA_TIT_ACTIVA_MATS,
    NVL(DO.N, 0)                                             AS DOC_OTRA_TIT_ACTIVA_FILAS,
    NVL(DO.NMAT, 0)                                          AS DOC_OTRA_TIT_ACTIVA_MATS,
    NVL(DO.NPERS, 0)                                         AS DOC_OTRA_TIT_ACTIVA_PERSONAS,
    B.CANT_REG_MISMA_MAT_PERSONA - 1                         AS OTRO_TIT_MISMA_PERS_Y_MAT,
    B.CANT_REG_MISMA_MAT_DOCUMENTO - 1                       AS OTRO_TIT_MISMO_DOC_Y_MAT,
    NVL(CO.N, 0)                                             AS MISMO_CASO_EN_MAT_REAL_FILAS,
    CO.MIN_ID                                                AS MISMO_CASO_MIN_ID_MAT_REAL,
    B.CANT_REG_MISMA_MAT_PERSONA, B.CANT_REG_MISMA_MAT_DOCUMENTO, B.CANT_PERSONAS_MISMA_MAT_DOC,
    TO_CHAR(B.FECHA_PRIMER_REGISTRO, 'YYYY-MM-DD HH24:MI:SS') AS FECHA_PRIMER_REGISTRO,
    TO_CHAR(B.FECHA_ULTIMO_REGISTRO, 'YYYY-MM-DD HH24:MI:SS') AS FECHA_ULTIMO_REGISTRO,
    B.ORDEN_EN_GRUPO, B.FILAS_HUERFANAS_PF_EN_ID,
    -- Historia de la persona / documento
    NVL(PB4.N, 0) AS PERSONA_B4_FILAS, NVL(PB4.N_MAT_EXISTENTE, 0) AS PERSONA_B4_MAT_EXISTENTE,
    NVL(DB4.N, 0) AS DOC_B4_FILAS, NVL(PB5.N, 0) AS PERSONA_B5_FILAS,
    -- Rastro del caso
    CB.CD_PROCESS AS CASO_CD_PROCESS, CB.CD_STATE AS CASO_ESTADO,
    TO_CHAR(CB.DT_INITIATED, 'YYYY-MM-DD HH24:MI:SS') AS CASO_DT_INICIO,
    TO_CHAR(CB.DT_TERMINATED, 'YYYY-MM-DD HH24:MI:SS') AS CASO_DT_FIN,
    NVL(CR.N_ASIENTOS, 0) AS CASO_R14_ASIENTOS, NVL(CR.NMAT_EXISTENTE, 0) AS CASO_R14_MAT_EXISTENTES,
    NVL(CR.NMAT_INEXISTENTE, 0) AS CASO_R14_MAT_INEXISTENTES, CR.MIN_ID_EXISTENTE AS CASO_R14_MIN_ID_EXISTENTE,
    -- Rastro del ID
    T.B2_FILAS_TOTAL_ID, T.B4_FILAS_ID, T.B5_FILAS_ID, T.R00_HIJAS_FILAS, T.R14_ASIENTOS_ID,
    T.B2_SNAPSHOT_2017_ID,
    (SELECT COUNT(*) FROM SIRCLAN.DIG_DOC_R00_B2_20170902 s
      WHERE s.ID_MATRICULA = B.ID_MATRICULA AND s.NU_SEQUENCE = B.NU_SEQUENCE
        AND s.CD_PERSONA = B.CD_PERSONA)                     AS FILA_EN_SNAPSHOT_2017,
    T.EN_PROCEDENCIA_MIG, T.EN_TOMOS_MAL_CREADOS, T.EN_SIRCWEB_R00,
    T.R00_ID_ANTERIOR,
    (SELECT TO_CHAR(i.DT_STORE, 'YYYY-MM-DD') FROM SIRCLAN.DIG_DOC_R00 i WHERE i.ID_MATRICULA = T.R00_ID_ANTERIOR) AS R00_ANTERIOR_DT_STORE,
    T.R00_ID_SIGUIENTE,
    (SELECT TO_CHAR(i.DT_STORE, 'YYYY-MM-DD') FROM SIRCLAN.DIG_DOC_R00 i WHERE i.ID_MATRICULA = T.R00_ID_SIGUIENTE) AS R00_SIGUIENTE_DT_STORE
FROM BASE B
JOIN TRAZA T ON T.ID = B.ID_MATRICULA
LEFT JOIN PER_OTRA PO ON PO.CD_PERSONA = B.CD_PERSONA
LEFT JOIN DOC_OTRA DO ON DO.NU_DOCUMENTO = B.DOC_OK
LEFT JOIN PER_B4 PB4 ON PB4.CD_PERSONA = B.CD_PERSONA
LEFT JOIN DOC_B4 DB4 ON DB4.NU_DOCUMENTO = B.DOC_OK
LEFT JOIN PER_B5 PB5 ON PB5.CD_PERSONA = B.CD_PERSONA
LEFT JOIN CASO_OTRA CO ON CO.NU_CASO_ORIGEN = B.NU_CASO_ORIGEN
LEFT JOIN CASO_R14 CR ON CR.NU_CASO = B.NU_CASO_ORIGEN
LEFT JOIN CASO_BPM CB ON CB.DOCUMENT_KEY_MAIN = B.NU_CASO_ORIGEN
ORDER BY B.ID_MATRICULA, B.CD_PERSONA, B.ORDEN_EN_GRUPO
